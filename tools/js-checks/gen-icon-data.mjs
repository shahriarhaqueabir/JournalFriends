// Generates src/js/components/animated-icons.data.js from the vendored
// animated SVGs so <hj-icon> needs no runtime fetch (CSP/origin-proof).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "src/assets/libs/animated-icons/lucide";
const OUT = "src/js/components/animated-icons.data.js";

const files = readdirSync(DIR).filter((f) => f.endsWith(".svg")).sort();
const entries = files.map((f) => {
  const name = f.replace(/\.svg$/, "");
  const svg = readFileSync(join(DIR, f), "utf8").replace(/\s+/g, " ").trim();
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`;
});

const out =
  `// AUTO-GENERATED by tools/js-checks/gen-icon-data.mjs — do not edit by hand.\n` +
  `// Inlined animated SVG markup for <hj-icon> (${files.length} icons).\n` +
  `export const ANIMATED_ICONS = {\n${entries.join("\n")}\n};\n`;

writeFileSync(OUT, out);
console.log(`wrote ${files.length} icons to ${OUT}`);
